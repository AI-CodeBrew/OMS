-- Leopards Courier integration - tables for Supabase (SQL editor).
--
-- Same thing as Django migration integrations/0026_leopards.py, as plain SQL,
-- for running by hand. Run it ONCE, BEFORE deploying the backend code that
-- uses it, and apply integrations 0025_smartlaneshipment first (this
-- migration comes after it).
--
-- Only NEW objects: the schema "leopards_integrations" and three tables in it.
-- Nothing that is already deployed reads or writes them, so it can't affect
-- the running backend. Safe to re-run (everything is "if not exists").
--
-- The last statement records the migration in django_migrations, so a later
-- `python manage.py migrate` sees it as applied and doesn't try to create
-- these tables again. (The AlterField on OmsCourierEnrollment.courier inside
-- that migration only widens a Python-side `choices` list - it has no SQL.)

begin;

create schema if not exists leopards_integrations;

-- ---------------------------------------------------------------- sync_jobs
create table if not exists "leopards_integrations"."sync_jobs" (
    "created_at" timestamp with time zone not null,
    "updated_at" timestamp with time zone not null,
    "id" uuid not null primary key,
    "status" varchar(10) not null,
    "cancel_requested" boolean not null,
    "checked_count" integer not null check ("checked_count" >= 0),
    "updated_count" integer not null check ("updated_count" >= 0),
    "total_available" integer null check ("total_available" >= 0),
    "error_message" varchar(500) not null,
    "started_at" timestamp with time zone null,
    "finished_at" timestamp with time zone null,
    "organization_id" uuid not null
        references "core"."organizations" ("id") deferrable initially deferred
);
create index if not exists "leopards_sync_jobs_organization_id_idx"
    on "leopards_integrations"."sync_jobs" ("organization_id");

-- -------------------------------------------------------------- connections
create table if not exists "leopards_integrations"."connections" (
    "id" bigint not null primary key generated by default as identity,
    "created_at" timestamp with time zone not null,
    "updated_at" timestamp with time zone not null,
    "api_key" varchar(255) not null,
    "api_password" varchar(255) not null,
    "is_connected" boolean not null,
    "shipper_name" varchar(255) not null,
    "origin_city_id" integer null check ("origin_city_id" >= 0),
    "origin_city_name" varchar(150) not null,
    "default_weight_grams" integer not null check ("default_weight_grams" >= 0),
    "default_shipment_type" varchar(50) not null,
    "default_notes" varchar(255) not null,
    "load_sheet_courier_name" varchar(100) not null,
    "load_sheet_courier_code" varchar(30) not null,
    "cities_cache" jsonb not null,
    "cities_cached_at" timestamp with time zone null,
    "city_aliases" jsonb not null,
    "last_synced_at" timestamp with time zone null,
    "webhook_token" uuid not null unique,
    "webhook_secret" varchar(64) not null,
    "last_event_at" timestamp with time zone null,
    "events_received_count" integer not null check ("events_received_count" >= 0),
    "recent_webhook_payloads" jsonb not null,
    "last_webhook_error" varchar(255) not null,
    "last_webhook_error_at" timestamp with time zone null,
    "organization_id" uuid not null
        references "core"."organizations" ("id") deferrable initially deferred,
    constraint "leopards_one_connection_per_org" unique ("organization_id")
);

-- ---------------------------------------------------------------- shipments
create table if not exists "leopards_integrations"."shipments" (
    "id" bigint not null primary key generated by default as identity,
    "created_at" timestamp with time zone not null,
    "updated_at" timestamp with time zone not null,
    "reference" varchar(100) not null,
    "tracking_number" varchar(100) not null,
    "slip_link" varchar(500) not null,
    "shipper_id" varchar(30) not null,
    "status_label" varchar(100) not null,
    "status_history" jsonb not null,
    "last_payload" jsonb not null,
    "is_active" boolean not null,
    "booked_at" timestamp with time zone not null,
    "load_sheet_id" varchar(50) not null,
    "load_sheet_at" timestamp with time zone null,
    "cancelled_at" timestamp with time zone null,
    "last_checked_at" timestamp with time zone null,
    "order_id" uuid not null
        references "oms"."orders" ("id") deferrable initially deferred,
    "organization_id" uuid not null
        references "core"."organizations" ("id") deferrable initially deferred,
    constraint "leopards_reference_unique_per_org" unique ("organization_id", "reference")
);
create index if not exists "leopards_shipments_order_id_idx"
    on "leopards_integrations"."shipments" ("order_id");
create index if not exists "leopards_shipments_organization_id_idx"
    on "leopards_integrations"."shipments" ("organization_id");
create index if not exists "leopards_shipment_poll_idx"
    on "leopards_integrations"."shipments" ("organization_id", "is_active", "last_checked_at");
create index if not exists "leopards_shipment_tn_idx"
    on "leopards_integrations"."shipments" ("organization_id", "tracking_number");
-- one live shipment per order (a cancelled one stays as history)
create unique index if not exists "leopards_one_active_shipment_per_order"
    on "leopards_integrations"."shipments" ("order_id") where "is_active";

-- ------------------------------------------------- row level security (RLS)
-- Same policy the PostEx / BarqRaftar tables carry (core.rls.
-- organization_scoped_policy_sql): a row is visible to its own organization
-- and to a super admin. Django itself bypasses RLS (pooler role), so this only
-- guards direct Postgres / PostgREST access - the tenant scoping Django relies
-- on is in the app.
alter table "leopards_integrations"."connections" enable row level security;
alter table "leopards_integrations"."connections" force row level security;
drop policy if exists connections_tenant_isolation on "leopards_integrations"."connections";
create policy connections_tenant_isolation on "leopards_integrations"."connections"
    for all
    using (core.is_super_admin() or organization_id = core.current_organization_id())
    with check (core.is_super_admin() or organization_id = core.current_organization_id());

alter table "leopards_integrations"."shipments" enable row level security;
alter table "leopards_integrations"."shipments" force row level security;
drop policy if exists shipments_tenant_isolation on "leopards_integrations"."shipments";
create policy shipments_tenant_isolation on "leopards_integrations"."shipments"
    for all
    using (core.is_super_admin() or organization_id = core.current_organization_id())
    with check (core.is_super_admin() or organization_id = core.current_organization_id());

alter table "leopards_integrations"."sync_jobs" enable row level security;
alter table "leopards_integrations"."sync_jobs" force row level security;
drop policy if exists sync_jobs_tenant_isolation on "leopards_integrations"."sync_jobs";
create policy sync_jobs_tenant_isolation on "leopards_integrations"."sync_jobs"
    for all
    using (core.is_super_admin() or organization_id = core.current_organization_id())
    with check (core.is_super_admin() or organization_id = core.current_organization_id());

-- ------------------------------------------- tell Django this is applied
insert into django_migrations (app, name, applied)
select 'integrations', '0026_leopards', now()
where not exists (
    select 1 from django_migrations where app = 'integrations' and name = '0026_leopards'
);

commit;
