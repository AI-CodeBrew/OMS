-- Smartlane shipment table (integrations migration 0025_smartlaneshipment) as
-- plain SQL for Supabase's SQL editor.
--
-- Run it ONCE, BEFORE integrations/leopards/sql/0026_leopards.sql (that
-- migration depends on this one). Requires 0024_omscourierenrollment_details to
-- be applied already (it is, if OMS Courier requests work in production).
--
-- Only a NEW table, "integrations"."smartlane_shipments" - nothing already
-- deployed reads or writes it, so it can't affect the running backend. Safe to
-- re-run (everything is "if not exists"). The migration itself creates no RLS
-- policy for it, so none is added here either.
--
-- The last statement records the migration in django_migrations, so a later
-- `python manage.py migrate` sees it as applied and doesn't try to create the
-- table again.

begin;

create table if not exists "integrations"."smartlane_shipments" (
    "id" bigint not null primary key generated by default as identity,
    "created_at" timestamp with time zone not null,
    "updated_at" timestamp with time zone not null,
    "account" varchar(50) not null,
    "store_id" varchar(50) not null,
    "store_order_id" varchar(100) not null,
    "consignment_id" varchar(50) not null,
    "consignment_number" varchar(100) not null,
    "batch_id" varchar(50) not null,
    "warehouse_code" varchar(100) not null,
    "warehouse_name" varchar(255) not null,
    "carrier" varchar(50) not null,
    "state" varchar(50) not null,
    "courier_status" varchar(255) not null,
    "courier_settlement" varchar(50) not null,
    "order_label" varchar(255) not null,
    "return_reason" varchar(255) not null,
    "qrcode_url" varchar(500) not null,
    "barcode_url" varchar(500) not null,
    "queued_at" timestamp with time zone null,
    "ready_at" timestamp with time zone null,
    "dispatched_at" timestamp with time zone null,
    "out_for_delivery_at" timestamp with time zone null,
    "attempted_at" timestamp with time zone null,
    "return_in_progress_at" timestamp with time zone null,
    "completed_at" timestamp with time zone null,
    "returned_at" timestamp with time zone null,
    "cancelled_at" timestamp with time zone null,
    "disputed_at" timestamp with time zone null,
    "tracking_history" jsonb not null,
    "last_payload" jsonb not null,
    "last_synced_at" timestamp with time zone null,
    "advice_reason" varchar(255) not null,
    "advice_actions" jsonb not null,
    "advice_expiry" varchar(50) not null,
    "advice_received_at" timestamp with time zone null,
    "last_advice_payload" jsonb not null,
    "order_id" uuid not null unique
        references "oms"."orders" ("id") deferrable initially deferred,
    "organization_id" uuid not null
        references "core"."organizations" ("id") deferrable initially deferred
);

create index if not exists "smartlane_shipments_organization_id_idx"
    on "integrations"."smartlane_shipments" ("organization_id");
create index if not exists "sl_shipment_settlement_idx"
    on "integrations"."smartlane_shipments" ("organization_id", "courier_settlement");
create index if not exists "sl_shipment_carrier_idx"
    on "integrations"."smartlane_shipments" ("organization_id", "carrier");

-- ------------------------------------------- tell Django this is applied
insert into django_migrations (app, name, applied)
select 'integrations', '0025_smartlaneshipment', now()
where not exists (
    select 1 from django_migrations
    where app = 'integrations' and name = '0025_smartlaneshipment'
);

commit;
