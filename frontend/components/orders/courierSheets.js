// The sheets "Import" reads onto existing orders (backend: oms/importers.py).
// A courier's own portal export, exactly as downloaded - `columns` is its full
// header row, `uses` the columns the import reads - or the courier
// aggregator's sheet ("other", the original format).

function rowsFor(columns, samples) {
  return samples.map((sample) => columns.map((column) => sample[column] ?? ""));
}

